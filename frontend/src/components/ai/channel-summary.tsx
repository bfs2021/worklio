"use client";

import { CalendarRange, ChevronDown, Clock3, Inbox, Loader2, Send, Settings2 } from "lucide-react";
import { useRouter } from "next/navigation";
import { useState } from "react";

import { SidePanel } from "@/components/chat/side-panel";
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuGroup,
  DropdownMenuItem,
  DropdownMenuLabel,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu";
import { useWorkspace } from "@/components/workspace/provider";
import { aiGateCopy, aiPaths, markdownToMessage, useAIGate, type SummaryRange } from "@/lib/ai";
import { api, type Message } from "@/lib/api";
import { errorMessage, toast } from "@/lib/toast";
import { cn } from "@/lib/utils";

import { openAsk } from "./ai-store";
import { AIDisabledState, AISparkle, AI_SURFACE } from "./brand";
import { ActionButton, StreamedAnswer } from "./streamed-answer";

export const RANGE_LABEL: Record<SummaryRange, string> = {
  unread: "Unread messages",
  "24h": "Last 24 hours",
  "7d": "Last 7 days",
  all: "Recent history",
};

const RANGES: { range: SummaryRange; label: string; icon: React.ComponentType<{ className?: string }> }[] = [
  { range: "unread", label: "Unread", icon: Inbox },
  { range: "24h", label: "Last 24 h", icon: Clock3 },
  { range: "7d", label: "Last 7 days", icon: CalendarRange },
];

/** Channel-header "✨ Summarize" menu. */
export function SummarizeMenu({ onPick, active, className }: { onPick: (r: SummaryRange) => void; active?: boolean; className?: string }) {
  const gate = useAIGate("summaries");
  const router = useRouter();
  const copy = gate.reason ? aiGateCopy(gate.reason, gate.canConfigure) : null;
  return (
    <DropdownMenu>
      <DropdownMenuTrigger
        className={cn(
          "flex h-7 shrink-0 items-center gap-1 rounded-md border px-1.5 text-[13px] font-semibold transition-colors hover:border-violet-500/40 hover:bg-violet-500/[0.06] sm:px-2",
          active && "border-violet-500/50 bg-violet-500/[0.08]",
          className,
        )}
        aria-label="Summarize with Worklio AI"
        title="Summarize with Worklio AI"
      >
        <AISparkle className="size-3.5" />
        <span className="hidden sm:inline">Summarize</span>
        <ChevronDown className="hidden size-3 text-muted-foreground sm:block" />
      </DropdownMenuTrigger>
      <DropdownMenuContent align="end" className="w-60">
        {copy ? (
          <DropdownMenuGroup>
            <DropdownMenuLabel className="flex items-center gap-1.5">
              <AISparkle className="size-3.5" /> {copy.title}
            </DropdownMenuLabel>
            <p className="px-2 pb-2 text-xs text-muted-foreground">{copy.body}</p>
            {copy.cta && (
              <DropdownMenuItem onClick={() => router.push(gate.settingsHref)} className="font-semibold">
                <Settings2 className="size-4" /> {gate.reason === "not_configured" ? "Set up Worklio AI" : "Open AI settings"}
              </DropdownMenuItem>
            )}
          </DropdownMenuGroup>
        ) : (
          <>
            <DropdownMenuGroup>
              <DropdownMenuLabel className="flex items-center gap-1.5">
                <AISparkle className="size-3.5" /> Summarize this conversation
              </DropdownMenuLabel>
              {RANGES.map((r) => (
                <DropdownMenuItem key={r.range} onClick={() => onPick(r.range)}>
                  <r.icon className="size-4" /> {r.label}
                </DropdownMenuItem>
              ))}
            </DropdownMenuGroup>
            <DropdownMenuSeparator />
            <DropdownMenuItem onClick={() => openAsk()}>
              <AISparkle className="size-4" /> Ask Worklio…
              <span className="ml-auto text-[11px] text-muted-foreground">⌘J</span>
            </DropdownMenuItem>
          </>
        )}
      </DropdownMenuContent>
    </DropdownMenu>
  );
}

/** Streaming channel summary in the right-hand panel, with "Post to channel" and "Copy". */
export function ChannelSummaryPanel({
  channelId,
  range,
  onRangeChange,
  onClose,
  onPosted,
}: {
  channelId: string;
  range: SummaryRange;
  onRangeChange: (r: SummaryRange) => void;
  onClose: () => void;
  onPosted?: (m: Message) => void;
}) {
  const ws = useWorkspace();
  const gate = useAIGate("summaries");
  const channel = ws.channels.find((c) => c.id === channelId);
  const isDM = channel?.kind === "dm";
  const label = channel ? (isDM ? ws.channelLabel(channel) : `#${ws.channelLabel(channel)}`) : "";
  const [posting, setPosting] = useState(false);
  const [posted, setPosted] = useState(false);

  const post = async (markdown: string) => {
    setPosting(true);
    try {
      const body = `✨ *Summary · ${RANGE_LABEL[range].toLowerCase()}* _(generated by Worklio AI)_\n\n${markdownToMessage(markdown)}`;
      const msg = await api<Message>(`/channels/${channelId}/messages`, {
        method: "POST",
        body: JSON.stringify({ body, parent_id: null, attachment_ids: [] }),
      });
      setPosted(true);
      onPosted?.(msg);
      toast.success(`Summary posted to ${label || "the conversation"}`);
    } catch (err) {
      toast.error(`Couldn't post the summary: ${errorMessage(err)}`);
    } finally {
      setPosting(false);
    }
  };

  return (
    <SidePanel
      title="Summary"
      subtitle={
        <span className="inline-flex items-center gap-1">
          <AISparkle className="size-3" /> {label}
        </span>
      }
      onClose={onClose}
    >
      <div className={cn("flex shrink-0 gap-1 overflow-x-auto border-b px-3 py-2 [scrollbar-width:none]", AI_SURFACE)} role="tablist" aria-label="Summary range">
        {RANGES.map((r) => (
          <button
            key={r.range}
            role="tab"
            aria-selected={range === r.range}
            onClick={() => {
              setPosted(false);
              onRangeChange(r.range);
            }}
            className={cn(
              "inline-flex h-7 shrink-0 items-center gap-1 rounded-full px-2.5 text-xs font-semibold transition-colors",
              range === r.range
                ? "bg-gradient-to-r from-violet-600 to-indigo-600 text-white shadow-sm"
                : "text-muted-foreground hover:bg-muted hover:text-foreground",
            )}
          >
            <r.icon className="size-3.5" /> {r.label}
          </button>
        ))}
      </div>
      <div className="min-h-0 flex-1 overflow-y-auto p-4">
        {gate.reason ? (
          <AIDisabledState feature="summaries" />
        ) : (
          <StreamedAnswer
            key={`${channelId}:${range}`}
            path={aiPaths.channelSummary(channelId)}
            body={{ range }}
            feature="summaries"
            thinking={range === "unread" ? "Reading your unread messages…" : "Reading the conversation…"}
            empty={range === "unread" ? "You're all caught up: there's nothing unread here." : "No messages in this period."}
            actions={(s) =>
              s.text && !s.error ? (
                <ActionButton primary onClick={() => post(s.text)} disabled={posting || posted || !!channel?.is_archived} title={channel?.is_archived ? "This channel is archived" : undefined}>
                  {posting ? <Loader2 className="size-3.5 animate-spin" /> : <Send className="size-3.5" />}
                  {posted ? "Posted" : "Post to channel"}
                </ActionButton>
              ) : null
            }
          />
        )}
      </div>
    </SidePanel>
  );
}
